"""Converts assets/brand/mk_logo_source.png to an LVGL 9 ARGB8888 image.

Usage (from repository root): python tools/asset_conversion/gen_logo.py [height] [name]
Requires Pillow. The generated C file is committed; the firmware build does not run this.
"""
import sys
from PIL import Image

height = int(sys.argv[1]) if len(sys.argv) > 1 else 120
src = Image.open("assets/brand/mk_logo_source.png").convert("RGBA")
src = src.crop(src.getchannel("A").getbbox())
width = round(src.width * height / src.height)
img = src.resize((width, height), Image.LANCZOS)

data = bytearray()
for r, g, b, a in img.getdata():
    data += bytes((b, g, r, a))  # ARGB8888 little-endian

name = sys.argv[2] if len(sys.argv) > 2 else "mk_logo_img"
out = f"lib/ui/src/assets/{name}.c"
with open(out, "w", newline="\n") as f:
    f.write("/* Generated by tools/asset_conversion/gen_logo.py - do not edit. */\n")
    f.write('#include "lvgl.h"\n\n')
    f.write(f"static const uint8_t {name}_data[] = {{\n")
    for i in range(0, len(data), 24):
        f.write("    " + ",".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",\n")
    f.write("};\n\n")
    f.write(f"const lv_image_dsc_t {name} = {{\n")
    f.write("    .header = {\n        .magic = LV_IMAGE_HEADER_MAGIC,\n")
    f.write("        .cf = LV_COLOR_FORMAT_ARGB8888,\n")
    f.write(f"        .w = {width},\n        .h = {height},\n        .stride = {width * 4},\n    }},\n")
    f.write(f"    .data_size = sizeof({name}_data),\n    .data = {name}_data,\n}};\n")
print(f"{out}: {width}x{height}, {len(data)} bytes")
